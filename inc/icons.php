/**
 * Return an inline SVG icon.
 *
 * @param string $name  Icon name.
 * @param string $class Extra CSS class.
 * @return string
 */
function fu_icon( $name, $class = '' ) {
	$icons = fu_icon_paths();
	if ( ! isset( $icons[ $name ] ) ) {
		$name = 'heart';
	}
	return sprintf(
		'<svg class="fu-icon %1$s" xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">%2$s</svg>',
		esc_attr( $class ),
		$icons[ $name ] // Static, trusted markup.
	);
}

/**
 * Icon choices for select controls.
 *
 * @return array
 */
function fu_icon_choices() {
	$out = array();
	foreach ( array( 'shield', 'heart', 'users', 'truck', 'target', 'hand-heart', 'file-text', 'building', 'credit-card', 'send', 'map-pin' ) as $k ) {
		$out[ $k ] = ucwords( str_replace( '-', ' ', $k ) );
	}
	return $out;
}
